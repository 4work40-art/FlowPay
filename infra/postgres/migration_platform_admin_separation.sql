-- ===========================================================================
-- Разделение администратора платформы и клиентских аккаунтов.
--
-- Было: platform-admin — это булев флаг users.is_platform_admin на обычной
-- строке в users, принадлежащей обычной клиентской организации. Такой аккаунт
-- логинился общим /auth/login и получал общий клиентский JWT; признак «админ
-- платформы» ехал внутри клиентского токена. Любая ошибка в клиентском
-- контуре (утечка/подделка клиентского токена, забытая проверка флага,
-- случайная выдача флага строке users прямым SQL) сразу означала полный
-- доступ ко всей платформе.
--
-- Стало: полностью отдельная таблица platform_admins и полностью отдельный
-- контур аутентификации (/api/v1/platform/login -> JWT с typ=platform_admin
-- -> platformAdminAuthMiddleware). Ни одной связи с organizations/users:
-- у платформенного администратора нет org_id и нет роли внутри организации.
--
-- Идемпотентно: миграция перезапускается на КАЖДОМ деплое (см. deploy.sh),
-- поэтому весь DDL — IF NOT EXISTS, а сид — ON CONFLICT DO NOTHING.
-- ===========================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ---------------------------------------------------------------------------
-- 1. Собственная таблица учётных записей платформы.
--    Осознанно БЕЗ org_id и без FK на users/organizations: запись здесь не
--    должна быть достижима ни из одной клиентской выборки.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS platform_admins (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email         VARCHAR(255) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  name          VARCHAR(255),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------------
-- 2. Единственная учётная запись владельца платформы.
--    Сид админа НАМЕРЕННО вынесен из этой миграции в deploy.sh: он генерирует
--    случайный пароль (openssl rand) при первой установке, хэширует его через
--    crypt/gen_salt('bf') и один раз показывает владельцу. Открытого пароля в
--    git больше нет — раньше он лежал прямо здесь и компрометировал god-mode
--    доступ ко всем организациям.
--    Вставка идемпотентна на стороне deploy.sh (INSERT ... WHERE NOT EXISTS),
--    поэтому повторный деплой не сбрасывает уже заданный владельцем пароль.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- 3. Defense-in-depth: снимаем флаг платформенного администратора со ВСЕХ
--    клиентских пользователей. Код его больше не читает и не кладёт в JWT,
--    но если где-то останется забытая проверка is_platform_admin — она
--    теперь не пропустит никого.
--
--    Колонка НЕ удаляется намеренно: DROP COLUMN на живой БД необратим и
--    ломает откат релиза, а пустая колонка ничего не стоит.
-- ---------------------------------------------------------------------------
UPDATE users SET is_platform_admin = false WHERE is_platform_admin = true;

-- ---------------------------------------------------------------------------
-- 4. Следы действий платформенного администратора.
--    audit_logs.user_id и subscription_events.created_by ссылаются на users(id)
--    внешним ключом — id из platform_admins туда физически не вписать (FK
--    violation: аудит бы молча терялся, а POST /admin/revenue-events падал бы
--    500). Добавляем отдельные колонки со своим FK вместо ослабления
--    существующих ограничений.
-- ---------------------------------------------------------------------------
ALTER TABLE audit_logs
  ADD COLUMN IF NOT EXISTS platform_admin_id UUID REFERENCES platform_admins(id) ON DELETE SET NULL;

ALTER TABLE subscription_events
  ADD COLUMN IF NOT EXISTS created_by_platform_admin UUID REFERENCES platform_admins(id) ON DELETE SET NULL;
