#!/bin/sh
set -e

# Каталог загрузок (/app/uploads) смонтирован как docker volume и на уже
# работающем проде принадлежит root (создан прежними root-контейнерами и
# хранит реальные вложения счетов/логотипы). Пока entrypoint выполняется под
# root, приводим владельца каталога к непривилегированному пользователю app,
# после чего СБРАСЫВАЕМ привилегии и запускаем node уже под app. Так рабочий
# процесс не имеет root в контейнере (меньше урон при RCE), но при этом может
# писать в существующий volume.
mkdir -p /app/uploads
chown -R app:app /app/uploads 2>/dev/null || true

exec su-exec app "$@"
