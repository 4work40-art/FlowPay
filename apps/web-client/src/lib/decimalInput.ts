// Клиентский фильтр для денежных/числовых полей ввода (сумма, цена,
// количество): пропускает только цифры и один разделитель дробной части
// (точку или запятую), отбрасывая всё остальное — буквы, минус, лишние
// разделители и т.п. Не заменяет серверную валидацию, а лишь не даёт
// пользователю случайно ввести заведомо мусорное значение вроде "-500abc".
export function sanitizeDecimalInput(raw: string): string {
  // Оставляем только цифры и разделители дробной части.
  const value = raw.replace(/[^0-9.,]/g, '');

  // Разрешаем только один разделитель: используем первый встретившийся,
  // остальные (включая повторы того же символа) отбрасываем.
  const firstSepIndex = value.search(/[.,]/);
  if (firstSepIndex === -1) return value;
  const before = value.slice(0, firstSepIndex + 1);
  const after = value.slice(firstSepIndex + 1).replace(/[.,]/g, '');
  return before + after;
}
